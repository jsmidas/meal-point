-- =========================================================
-- v43: 판매 금액을 그대로 기록 (2026-11-19)
--
-- inventory_logs.unit_price 는 개당 단가(정수)다. 박스 단가가 입수로 나누어떨어지지 않으면
-- (예: 박스 50,000원 / 300개 = 개당 166.67원) 개당 단가가 167원으로 반올림되어
-- 금액이 50,100원으로 기록됐다.
--
-- amount 는 그 줄의 판매 금액(공급가, 원)이다.
--   - 값이 있으면 그 금액이 그대로 매출·정산·손익·명세서에 쓰인다.
--   - NULL 이면 예전처럼 quantity * unit_price 로 계산한다. (기존 기록은 모두 NULL → 금액 변화 없음)
--
-- 실행 순서: 이 SQL 을 먼저 실행한 뒤에 새 코드를 배포한다.
--   (새 코드는 amount 컬럼을 읽고 쓰므로 컬럼이 없으면 판매·정산 화면이 열리지 않는다.
--    컬럼만 먼저 추가된 상태에서는 예전 코드도 그대로 동작한다.)
-- =========================================================

ALTER TABLE public.inventory_logs ADD COLUMN IF NOT EXISTS amount INT;

COMMENT ON COLUMN public.inventory_logs.amount IS
  '판매 금액(공급가, 원). NULL 이면 quantity * unit_price. 박스 단가가 입수로 나누어떨어지지 않을 때 박스 금액을 그대로 남긴다.';
